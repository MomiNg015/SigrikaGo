def load_base_module():
    spec = importlib.util.spec_from_file_location("huanglong_base", BASE_SCRIPT)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load base script: {BASE_SCRIPT}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def assert_second_revision(output: Path, base) -> None:
    document = Document(output)
    keyed = base.collect_keyed_paragraphs(document)
    text = base.visible_text(keyed)

    forbidden = (
        "——",
        "不是……而是",
        "并非……而是",
        "与其说",
        "不如说",
        "说到底",
        "真正的问题",
        "更深一层",
    )
    for term in forbidden:
        if term in text:
            raise RuntimeError(f"Second-revision prose check failed: {term}")

    if "：" in text:
        raise RuntimeError("Second-revision prose check failed: full-width colon")

    if keyed["P149"].text != "旁白" or keyed["P153"].text != "旁白":
        raise RuntimeError("Dream narration labels were not updated")

    for key, expected in REVISED_REPLACEMENTS.items():
        if keyed[key].text != expected:
            raise RuntimeError(f"Second-revision text mismatch: {key}")

    print("second_revision_content_check=passed")


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: rewrite_story_second_revision.py SOURCE OUTPUT")

    base = load_base_module()
    base.REPLACEMENTS.update(REVISED_REPLACEMENTS)
    base.main()
    assert_second_revision(Path(sys.argv[2]).resolve(), base)


if __name__ == "__main__":
    main()
