import { readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { CHARACTER_PORTRAIT_ASSETS, COSTUME_PORTRAIT_ASSETS } from '../src/shared/characterPortraitAssetCatalog.js';
import { CHARACTER_CHIBI_LANDMARKS, characterChibiSource } from '../src/shared/characterChibiPortraits.js';

const urls = [...new Set([
  ...Object.keys(CHARACTER_CHIBI_LANDMARKS).map(id => characterChibiSource(id)),
  ...Object.values(CHARACTER_PORTRAIT_ASSETS).flatMap(a => [a.url, a.legacyUrl]),
  ...Object.values(COSTUME_PORTRAIT_ASSETS).flatMap(a => [a.url, a.legacyUrl]),
])].sort();
const bounds = {};
for (const url of urls) {
  const input = await readFile(new URL(`../public${url}`, import.meta.url));
  const meta = await sharp(input, { animated: true }).metadata();
  const { data, info } = await sharp(input, { animated: true }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const height = meta.pageHeight || info.height;
  let left=info.width, top=height, right=-1, bottom=-1;
  for(let y=0;y<info.height;y++) for(let x=0;x<info.width;x++) {
    if(data[(y*info.width+x)*info.channels+info.channels-1] < 16) continue;
    const frameY=y%height;
    left=Math.min(left,x);top=Math.min(top,frameY);right=Math.max(right,x);bottom=Math.max(bottom,frameY);
  }
  if(right<left) throw new Error(`Empty portrait: ${url}`);
  bounds[url]=[info.width,height,left,top,right-left+1,bottom-top+1];
}
const output = new URL('../src/shared/portraitVisibleBounds.js', import.meta.url);
const source = `// Generated by scripts/export-portrait-visible-bounds.mjs; animated assets use the union of all frames.\nexport const PORTRAIT_VISIBLE_BOUNDS = ${JSON.stringify(bounds,null,2)};\n`;
if (process.argv.includes('--check')) {
  const existing = (await readFile(output, 'utf8')).replace(/\r\n/g, '\n');
  if (existing !== source) throw new Error('Portrait bounds are stale; run node scripts/export-portrait-visible-bounds.mjs');
  console.log(`Verified visible bounds for ${urls.length} portraits.`);
} else {
  await writeFile(output, source);
  console.log(`Measured ${urls.length} portraits without modifying source pixels.`);
}
